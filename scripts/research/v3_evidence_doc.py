"""Render docs/research/EVIDENCE_MAP_V3.md from data/research/corpus/evidence_map_v3.json.

Generated document: edit evidence_map_v3_spec.json or claim_check_v3_spec.json and
re-run ``python3 scripts/research/v3_evidence.py evidence-map``; never edit the
Markdown by hand (``v3_evidence.py verify`` checks it carries the current hash).
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

CORPUS = Path("data/research/corpus")
EMAP = CORPUS / "evidence_map_v3.json"
CLAIM = CORPUS / "claim_check_v3.json"
GAP = Path("data/research/v3_gap_search/2026-10-26_search-1.2")  # latest frozen run; v1.0 and v1.1 stay frozen
DOC = Path("docs/research/EVIDENCE_MAP_V3.md")

BAND_LABEL = {
    "includes_15_17_explicit": "ages incl. 15-17 (accepted explicit range)",
    "minors_possible_unverified": "youth/minors possible (ages unverified)",
    "conflicting_explicit_ranges": "conflicting age ranges (ages unverified)",
    "review_eligibility_includes_minors": "review; eligibility includes minors (not one sample)",
    "review_eligibility_adults_only": "review; adults-only eligibility",
    "adults_only_explicit": "adults only (accepted explicit range)",
    "adults_indexed_or_named_only": "adults (MeSH or title words)",
    "not_stated": "ages not stated",
}
ROLE_MARK = {"supports_for_minors": " (minors)", "context_for_minors": " (minors context, ages unverified)"}
AGE_GROUP_LABEL = {
    "includes_15_17_explicit": "ages 15-17 included (accepted explicit range, usually mixed with older ages)",
    "minors_signal_ages_unverified": "minors signal, ages unverified",
    "adults_only": "adults only (explicit range, adult-only review, or adult MeSH/title words)",
    "ages_not_stated": "ages not stated",
}
RELATION = {"direct": "direct", "adjacent": "adjacent", "indirect": "context only"}


def _esc(text):
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ")


def _short(title, n=90):
    t = " ".join(str(title or "").split())
    return t if len(t) <= n else t[: n - 1].rstrip() + "…"


def _design(s):
    d = s["design_machine_label"] or "unknown"
    return d + (" ⚠ label caution" if s.get("design_caution") else "")


def render(root):
    root = Path(root)
    emap_bytes = (root / EMAP).read_bytes()
    emap = json.loads(emap_bytes)
    claim = json.loads((root / CLAIM).read_text(encoding="utf-8")) if (root / CLAIM).exists() else None
    gm = json.loads((root / GAP / "manifest.json").read_text(encoding="utf-8")) if (root / GAP / "manifest.json").exists() else None
    sm = (json.loads((root / GAP / "screening" / "manifest.json").read_text(encoding="utf-8"))
          if (root / GAP / "screening" / "manifest.json").exists() else None)
    L = []
    a = L.append
    a("# v3 evidence map")
    a("")
    a(f"Status: **machine-assembled, agent-drafted, unreviewed** (`{emap['map_version']}`, freeze date {emap['freeze_date']}, "
      f"cutoff {emap['cutoff_date']}). Generated by `python3 scripts/research/v3_evidence.py evidence-map` from "
      "[evidence_map_v3.json](../../data/research/corpus/evidence_map_v3.json); do not edit this file by hand. "
      "This document is non-normative; [SPEC.md](../../SPEC.md) stays authoritative. Supports research audit tasks R-8 and R-9 "
      "and decision D-048.")
    a("")
    a("## What this is, and what it is not")
    a("")
    a("- **One row per v3 feature.** Each row lists the register records that bear on it, with their machine design label and "
      "their age band, the counter-evidence, the claim boundary, the declared gaps, and the v3 gap-search candidates queued for "
      "human screening.")
    a("- **Not appraisal.** No record was read in full or assessed for risk of bias by a person. The register records keep "
      "`reviewer_status: not_reviewed`; their inclusion is the inherited title/abstract screening. The v3 candidates are "
      f"machine-screened only (`{sm['screening_version'] if sm else 'not run'}`) and are reading lists, not evidence.")
    a("- **Adults and minors are kept apart.** A record supports something for ages 15-17 only if its machine age band is "
      "`includes_15_17_explicit`: the age range the pipeline accepted for a primary study (one consistent explicit "
      "full-text range, not a review's eligibility rule, not one of several conflicting candidates, not an advisory "
      "group's ages) overlaps 15-17. Even then it holds only within its own limits. Records with a minors signal but "
      "no such range appear in the minors row as context with ages unverified. Adult evidence is never cited for "
      "minors mode.")
    a("- **Associations are not effects.** Cohorts, cross-sectional surveys and secondary analyses are read as associations, "
      "whatever their abstracts conclude.")
    a("- **Product use.** These rows inform product decisions and educational copy. They are not citations to attach to "
      "empathic replies, and none of them shows that Sela works or is safe.")
    a("")
    for line in emap["how_to_read"]:
        a(f"> {line}")
    a("")
    c = emap["counts"]
    a("## Summary")
    a("")
    a(f"- Features mapped: **{c['features']}**.")
    a("- Features with **no direct register evidence**: " + ", ".join(f"`{x}`" for x in c["features_without_direct_register_support"]) + ".")
    a("- Features whose register support comes only from adults or unstated ages: "
      + ", ".join(f"`{x}`" for x in c["features_supported_by_adult_or_unstated_ages_only"]) + ".")
    if "candidates_shown" in c:
        dis = c["candidates_shown_language_disagrees_with_indonesian_title"]
        a(f"- Language of the {c['candidates_shown']} candidates shown below is metadata, not a reading of the paper. "
          f"{len(dis)} of them have an Indonesian-looking title but a recorded language other than Indonesian"
          + (f" ({', '.join(dis)})" if dis else "") + f"; {len(c['candidates_shown_language_inferred_only'])} have a "
          "language inferred by OpenAlex only, and " + str(len(c["candidates_shown_language_not_stated"]))
          + " have none. The Language column shows the basis: 'indexed' (Europe PMC), 'deposited' (Crossref), "
          "'inferred' (OpenAlex), and 'title suggests id' where the title cue disagrees.")
    if gm and sm:
        gc = gm["counts"]
        a(f"- New frozen gap search ({gm['run_version']}): **{gc['candidates']}** metadata-only candidates from Europe PMC and "
          f"Crossref ({gc['only_crossref']} found only through Crossref), {gc['abstract_available']} with an abstract used for "
          f"machine screening (abstract text is not committed). Machine screening: "
          + ", ".join(f"{k} {v}" for k, v in sm["priority_counts"].items()) + f"; queue {sm['queue_count']}. "
          "See [V3_GAP_SEARCH.md](V3_GAP_SEARCH.md).")
    if claim:
        cc = claim["counts"]
        a(f"- Claim check of docs 07/10 (R-9): {cc['statements']} statements, {cc['assertions']} assertions; "
          + ", ".join(f"{k} {v}" for k, v in cc["assertion_status"].items())
          + f"; {cc['mismatches']} mismatches and {len(cc['wording_issues'])} wording "
          + ("issue" if len(cc["wording_issues"]) == 1 else "issues") + " (section below).")
    a("")
    a("## Brief section 9 topics")
    a("")
    a("| Topic | Feature rows | Register records tagged for this topic |")
    a("| --- | --- | --- |")
    order = list(emap.get("brief_section_9_topics") or [])
    for t, v in sorted(emap["brief_topics"].items(), key=lambda kv: (
            order.index(kv[0]) if kv[0] in order else len(order), kv[0])):
        a(f"| {_esc(t)} | {', '.join('`' + x + '`' for x in v['features']) or 'none'} | "
          f"{', '.join(v['register_ids']) or 'none'} |")
    a("")
    a("A record counts for a topic only when it is tagged for that topic (or its row has that topic alone); the "
      "table is never the union of every record of every row that lists the topic. So the clinician-facing "
      "summarisation records of the consultation-summary and memory-correction rows count as consultation "
      "preparation evidence only, not as continuity or listening evidence. Help-seeking has its own row. 'Adults' "
      "(dewasa) has its own row for working-age and mid-life adults beyond students; 'adults (computed from age "
      "bands)' lists every cited record whose machine age band is adult-only (an adult-only range or review "
      "eligibility, adult MeSH or title words, or conflicting candidates that all start at 18). Adults are the "
      "default population of most register evidence, which is why every row states its age groups.")
    a("")
    for row in emap["features"]:
        a(f"## {row['feature']}")
        a("")
        a(f"*Question.* {row['question']}")
        a("")
        if row.get("brief_topics_note"):
            a(f"*Brief topics.* {row['brief_topics_note']}")
            a("")
        if row["register_support"]:
            a("| Record | Relation | Brief topics | Design (machine label) | Age band (machine) | Inference (agent, "
              "unreviewed) | Country / language terms | Title |")
            a("| --- | --- | --- | --- | --- | --- | --- | --- |")
            for s in row["register_support"]:
                a(f"| {s['id']} | {RELATION.get(s['relation'], s['relation'])}{ROLE_MARK.get(s['role'], '')} "
                  f"| {_esc(', '.join(s.get('topics', [])) or 'context only')} "
                  f"| {_esc(_design(s))} | {_esc(BAND_LABEL.get(s['age_band'], s['age_band']))} "
                  f"| {_esc(s.get('inference_label') or '-')} "
                  f"| {_esc(', '.join(s['country_or_language'] or []) or '-')} | {_esc(_short(s['title']))} |")
            a("")
            notes = [s for s in row["register_support"] if s.get("note")]
            if notes:
                a("Notes (agent reading of the public abstract, unreviewed):")
                a("")
                for s in notes:
                    a(f"- {s['id']}: {s['note']}.")
                a("")
        else:
            a("No register record bears on this feature.")
            a("")
        groups = row.get("support_age_groups") or {}
        if any(groups.values()):
            a("Age groups of the cited register records (evidence from one group is not read for another): " + "; ".join(
                f"{AGE_GROUP_LABEL[k]}: {', '.join(groups.get(k) or []) or 'none'}" for k in AGE_GROUP_LABEL) + ".")
            a("")
        split = row["support_population_split"]
        if split:
            a("Machine age bands: " + "; ".join(
                f"{BAND_LABEL.get(k, k)}: {', '.join(v)}" for k, v in split.items()) + ".")
            a("")
        tc = row.get("theme_coverage")
        if tc:
            excl = tc["deliberately_excluded"]
            a(f"Coverage of register theme {tc['theme']}: {len(tc['cited'])} of {len(tc['records_in_theme'])} records "
              f"cited ({', '.join(tc['cited'])}); deliberately excluded: "
              + ("; ".join(f"{e['id']} ({e['reason']})" for e in excl) if excl else "none")
              + (f"; NOT COVERED: {', '.join(tc['uncovered'])}" if tc["uncovered"] else "") + ".")
            a("")
        if row["counter_evidence"]:
            a("**Counter-evidence and limits**")
            a("")
            for s in row["counter_evidence"]:
                a(f"- {s['id']} ({_esc(s['design_machine_label'])}; {_esc(BAND_LABEL.get(s['age_band'], s['age_band']))}): {s['reason']}.")
            a("")
        a(f"**Claim boundary.** {row['claim_boundary']}")
        a("")
        a("**Declared gaps**")
        a("")
        for g in row["declared_gaps"]:
            a(f"- {g}")
        a("")
        v = row["v3_candidates_for_human_screening"]
        a(f"**v3 candidates queued for human screening:** {v['count_in_queue']} in the 400-row queue "
          f"(families: {', '.join('`' + f + '`' for f in row.get('families', []))}). Top rows, machine-ranked:")
        a("")
        if v["top"]:
            a("| Candidate | Priority | Population band (machine) | Language | Null/negative cue | Title |")
            a("| --- | --- | --- | --- | --- | --- |")
            for q in v["top"][:5]:
                a(f"| {q['candidate_id']}{' = ' + q['in_register'] if q.get('in_register') else ''} | {q['machine_priority']} "
                  f"| {_esc(q['population_band'])} | {_esc(q.get('language_display') or q['publication_language'] or 'not stated')} "
                  f"| {'yes' if q['possible_null_or_negative_finding'] else '-'} | {_esc(_short(q['title']))} |")
            a("")
        a(f"*Before any stronger claim:* {row['required_before_stronger_claims']}")
        a("")
    if claim:
        a("## Claim check of docs 07 and 10 (R-9)")
        a("")
        a(f"Status: `{claim['status']}`. {claim['method']}")
        a("")
        a("| Statement | Doc location | Cited | Machine result | Agent reading (unreviewed) |")
        a("| --- | --- | --- | --- | --- |")
        for s in claim["statements"]:
            a(f"| {s['id']} | {_esc(s['location'])} | {', '.join(s['cited'])} | {s['overall']} | {_esc(s['agent_reading'])} |")
        a("")
        a("**Mismatches** (an assertion whose terms were not all found, or no open abstract):")
        a("")
        for m in claim["mismatches"]:
            a(f"- {m['statement']} {m['assertion']} ({m['status']}): {m['claim_part']}." + (f" {m['note']}." if m.get("note") else ""))
        a("")
        a("**Wording issues** (the source supports the finding, but the wording overstates it):")
        a("")
        for w in claim["wording_issues"]:
            a(f"- {w['statement']} \u201c{w['statement_text']}\u201d: {w['issue']}")
        a("")
        a("The non-peer-reviewed Stanford news item cited in doc 10 was not checked; doc 10 now carries a dated note pointing "
          "to R099, the peer-reviewed paper.")
        a("")
    a("## Provenance")
    a("")
    a(f"- evidence_map_v3.json sha256 `{hashlib.sha256(emap_bytes).hexdigest()}`")
    for rel, digest in sorted(emap["inputs"].items()):
        stored_gz = rel.startswith("data/research/v3_gap_search/") and rel.endswith("/candidates.jsonl")
        a(f"- input `{rel}` sha256 `{digest}`" + (" (committed as `candidates.jsonl.gz`; the hash is of the "
                                                  "uncompressed content)" if stored_gz else ""))
    a("- Rows and claim decompositions were drafted by the AI research agent on 2026-10-26 from the register annotations, "
      "the machine record fields and the public abstracts (read from a local, gitignored cache). They need human review "
      "before any of them is quoted as an evidence statement (blocker B-4).")
    a("")
    (root / DOC).write_text("\n".join(L), encoding="utf-8")
    return root / DOC
